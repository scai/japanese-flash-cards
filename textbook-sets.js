// Transcribed from the user's images. Rows: Japanese | reading | Chinese | optional verb group.
// Keep each image's section and entry order. Accent lines and editorial asterisks are omitted.
function textbookSet(number, title, source, expectedCount, rows) {
  const cards = rows.trim().split('\n').map(row => {
    const [japanese, reading, meaning, group] = row.split('|').map(value => value.trim());
    return {japanese, reading, chinese:meaning + (group ? `（動詞 ${group}）` : '')};
  });
  if (cards.length !== expectedCount || cards.some(card => !card.japanese || !card.reading || !card.chinese)) {
    throw new Error(`Invalid textbook data for lesson ${number}`);
  }
  return {id:`lesson-${number}`,number,name:`第 ${number} 课 · ${title}`,source,cards};
}
